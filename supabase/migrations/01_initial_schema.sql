-- ==============================================================================
-- VoltFlow Smart Home - Supabase PostgreSQL Schema & Realtime Setup
-- Table Names: device_state, device_commands, device_events
-- Device Identifier Default: esp32-home-01
-- ==============================================================================

-- 1. DEVICE STATE TABLE
-- Holds the live synchronized state and heartbeat of each hardware gateway
CREATE TABLE IF NOT EXISTS public.device_state (
  device_id TEXT PRIMARY KEY,
  light_on BOOLEAN NOT NULL DEFAULT false,
  eco_mode BOOLEAN NOT NULL DEFAULT true,
  fan_speed INTEGER NOT NULL DEFAULT 0 CHECK (fan_speed >= 0 AND fan_speed <= 255),
  motor_on BOOLEAN NOT NULL DEFAULT false,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Optional timer extensions (safe to run if you wish to report hardware countdowns in Supabase)
ALTER TABLE public.device_state ADD COLUMN IF NOT EXISTS light_timer_active BOOLEAN DEFAULT false;
ALTER TABLE public.device_state ADD COLUMN IF NOT EXISTS light_timer_remaining INTEGER DEFAULT 0;
ALTER TABLE public.device_state ADD COLUMN IF NOT EXISTS light_timer_action TEXT DEFAULT '';
ALTER TABLE public.device_state ADD COLUMN IF NOT EXISTS fan_timer_active BOOLEAN DEFAULT false;
ALTER TABLE public.device_state ADD COLUMN IF NOT EXISTS fan_timer_remaining INTEGER DEFAULT 0;
ALTER TABLE public.device_state ADD COLUMN IF NOT EXISTS fan_timer_action TEXT DEFAULT '';

-- 2. DEVICE COMMANDS TABLE
-- Enqueued by Web/Mobile clients, polled and acknowledged by ESP32
CREATE TABLE IF NOT EXISTS public.device_commands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL,
  device TEXT NOT NULL,                  -- 'light', 'fan', 'motor'
  action TEXT NOT NULL,                  -- 'on', 'off', 'speed', 'eco', 'normal', 'set_timer'
  value NUMERIC DEFAULT 0,               -- 1/0 for light, 0/80/150/255 for fan
  duration_seconds INTEGER DEFAULT 0,    -- timer duration in seconds
  timer_action TEXT DEFAULT 'off',       -- 'on' or 'off' target action
  status TEXT NOT NULL DEFAULT 'pending',-- 'pending', 'executing', 'completed', 'failed'
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ
);

-- Indexes for lightning fast command polling by ESP32
CREATE INDEX IF NOT EXISTS idx_device_commands_poll 
  ON public.device_commands (device_id, status, created_at ASC);

-- 3. DEVICE EVENTS TABLE
-- Immutable event stream of actual physical transitions logged by ESP32
CREATE TABLE IF NOT EXISTS public.device_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL,
  device TEXT NOT NULL,                  -- 'light', 'fan', 'motor'
  event_type TEXT NOT NULL,              -- 'turned_on', 'turned_off', 'speed_change', 'motion_on', 'motion_off', 'timer_expired'
  value NUMERIC DEFAULT 0,               -- PWM value or binary state
  source TEXT DEFAULT 'esp32',           -- 'mobile', 'web', 'PIR', 'timer', 'physical'
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indexes for fast analytics, date filtering, and duration pairing
CREATE INDEX IF NOT EXISTS idx_device_events_analytics 
  ON public.device_events (device_id, device, occurred_at ASC);

-- ==============================================================================
-- 4. REALTIME PUBLICATION SETUP
-- Enables instant WebSocket pushes to browser clients when state/events change
-- ==============================================================================
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.device_state;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.device_commands;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.device_events;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;
END $$;

-- ==============================================================================
-- 5. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================
ALTER TABLE public.device_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_commands ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_events ENABLE ROW LEVEL SECURITY;

-- Prototype / Anon access policies (for public anon key client usage)
CREATE POLICY "Allow public read access to device_state"
  ON public.device_state FOR SELECT
  USING (true);

CREATE POLICY "Allow public upsert access to device_state"
  ON public.device_state FOR ALL
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Allow public read access to device_commands"
  ON public.device_commands FOR SELECT
  USING (true);

CREATE POLICY "Allow public insert and update to device_commands"
  ON public.device_commands FOR ALL
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Allow public read access to device_events"
  ON public.device_events FOR SELECT
  USING (true);

CREATE POLICY "Allow public insert to device_events"
  ON public.device_events FOR INSERT
  WITH CHECK (true);
